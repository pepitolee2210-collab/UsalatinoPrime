interface MetadataInput {
  full_name: string
  a_number?: string | null
  date_of_birth?: string | null
  city_country_of_birth?: string | null
  current_nationality?: string | null
  date_entered_us?: string | null
  port_of_entry?: string | null
  days_since_entry?: number | null
  marital_status?: string | null
  current_us_address?: string | null
  native_language?: string | null
}

interface UploadedDocInput {
  document_id: string
  filename: string
  declared_category: string | null
  language?: string | null
  detected_dates?: string[]
  detected_names?: string[]
  detected_places?: string[]
  extracted_text?: string | null
}

interface EvidenceLinkInput {
  url: string
  title?: string | null
  source_organization?: string | null
  category?: string | null
  description?: string | null
  scraped_content?: string | null
}

export interface BuildAnalysisUserPromptInput {
  applicantMetadata: MetadataInput
  questionnaireResponsesJson: Record<string, unknown>
  uploadedDocuments: UploadedDocInput[]
  evidenceLinks: EvidenceLinkInput[]
}

export function buildAnalysisUserPrompt(input: BuildAnalysisUserPromptInput): string {
  return buildBaseInputs(input) +
    '\n\nAnalyze the inputs and return the analysis JSON (without the declaration) following the schema in the system prompt. ONLY JSON, no prose, no code fences.'
}

export interface BuildDeclarationUserPromptInput extends BuildAnalysisUserPromptInput {
  /** Raw JSON output from the first call (analysis). Passed as-is for consistency. */
  analysisJson: string
  /** Optional country conditions block (Tavily/scrape) for visibility. */
  countryConditionsBlock?: string
}

export function buildDeclarationUserPrompt(input: BuildDeclarationUserPromptInput): string {
  const parts: string[] = []
  parts.push(buildBaseInputs(input))
  if (input.countryConditionsBlock) {
    parts.push('')
    parts.push(input.countryConditionsBlock)
  }
  parts.push('')
  parts.push('<analysis_output_from_previous_call>')
  parts.push('This is the structured case analysis already produced. USE it for consistency (same protected grounds, same dates, same identified perpetrator, same exhibit numbers). DO NOT repeat the analysis — write ONLY the declaration following the I-VI structure in ENGLISH.')
  parts.push(input.analysisJson)
  parts.push('</analysis_output_from_previous_call>')
  parts.push('')
  parts.push('Draft the declaration in ENGLISH (3000-5000 words) in I-VI structure following ALL the rules of the system prompt. Cite specific URLs in section VI with title + medium + date. Cite country statistical data and emblematic cases in section III. CRITICAL R11: do NOT include "I declare under penalty of perjury..." inside the paragraphs of section VI — that closing goes ONLY in the closing_attestation field. Return ONLY the JSON {declaration_es, cited_urls_in_body, factual_claims_audit, declaration_total_words}. No prose, no code fences.')
  return parts.join('\n')
}

function buildBaseInputs(input: BuildAnalysisUserPromptInput): string {
  const md = input.applicantMetadata
  const lines: string[] = []
  lines.push('<applicant_metadata>')
  lines.push(`Full name: ${md.full_name}`)
  if (md.a_number) lines.push(`A-Number: ${md.a_number}`)
  if (md.date_of_birth) lines.push(`Date of birth: ${md.date_of_birth}`)
  if (md.city_country_of_birth) lines.push(`City and country of birth: ${md.city_country_of_birth}`)
  if (md.current_nationality) lines.push(`Current nationality: ${md.current_nationality}`)
  if (md.date_entered_us) lines.push(`Date of last entry to U.S.: ${md.date_entered_us}`)
  if (md.port_of_entry) lines.push(`Place of entry: ${md.port_of_entry}`)
  if (md.days_since_entry != null) lines.push(`Days since entry: ${md.days_since_entry}`)
  if (md.marital_status) lines.push(`Marital status: ${md.marital_status}`)
  if (md.current_us_address) lines.push(`Current U.S. address: ${md.current_us_address}`)
  if (md.native_language) lines.push(`Native language: ${md.native_language}`)
  lines.push('</applicant_metadata>')
  lines.push('')

  lines.push('<questionnaire_responses>')
  lines.push(JSON.stringify(input.questionnaireResponsesJson, null, 2))
  lines.push('</questionnaire_responses>')
  lines.push('')

  lines.push('<uploaded_documents>')
  if (input.uploadedDocuments.length === 0) {
    lines.push('(none)')
  } else {
    for (const doc of input.uploadedDocuments) {
      lines.push(
        `<document id="${doc.document_id}" category="${doc.declared_category ?? 'unknown'}" language="${doc.language ?? 'unknown'}">`,
      )
      if (doc.filename) lines.push(`  filename: ${doc.filename}`)
      if (doc.detected_dates?.length) lines.push(`  detected_dates: ${doc.detected_dates.join(', ')}`)
      if (doc.detected_names?.length) lines.push(`  detected_names: ${doc.detected_names.join(', ')}`)
      if (doc.detected_places?.length) lines.push(`  detected_places: ${doc.detected_places.join(', ')}`)
      if (doc.extracted_text) {
        lines.push('  extracted_text:')
        lines.push('  """')
        lines.push(doc.extracted_text.slice(0, 4000))
        lines.push('  """')
      }
      lines.push('</document>')
    }
  }
  lines.push('</uploaded_documents>')
  lines.push('')

  lines.push('<evidence_links>')
  if (input.evidenceLinks.length === 0) {
    lines.push('(none)')
  } else {
    for (const link of input.evidenceLinks) {
      lines.push(
        `<link url="${link.url}" source="${link.source_organization ?? ''}" category="${link.category ?? ''}">`,
      )
      if (link.title) lines.push(`  title: ${link.title}`)
      if (link.description) lines.push(`  description: ${link.description}`)
      if (link.scraped_content) {
        lines.push('  excerpt:')
        lines.push('  """')
        lines.push(link.scraped_content.slice(0, 2000))
        lines.push('  """')
      }
      lines.push('</link>')
    }
  }
  lines.push('</evidence_links>')
  return lines.join('\n')
}
